#!/usr/bin/env python3
"""Pi-only replay of real 900-row CSV: trusted RF500 -> candidate UART packet.

Run via SSH stdin with the isolated RF30 virtualenv. There is NO physical UART
open and no serial write. The mock MCU ACK tests the handshake interface only.
This is NOT blind model accuracy testing, not production model promotion.
"""
from __future__ import annotations

import csv
import hashlib
import json
from pathlib import Path
import sys

BASE=Path.home()/"smart-coffee-stage7"/"rf30_staging"
sys.path.insert(0,str(BASE))

import sklearn
from roast_rf30_pi_inference import EXPECTED_SHA, ADC_COLUMNS, verify_artifact
from rf30_pi_result_bridge import BUILD_ID, HostSession, wire_command

assert sklearn.__version__=="1.7.2"
model=BASE/"final_model.joblib"
meta=BASE/"final_model_info.json"
sha=verify_artifact(model,meta)["sha256"]
assert sha==EXPECTED_SHA

path=BASE/"D-CAT_B70.csv"
with path.open(newline="",encoding="utf-8-sig") as f:
    rows=list(csv.DictReader(f))
assert len(rows)==900
source_digest=hashlib.sha256(path.read_bytes()).hexdigest()
assert source_digest=="4800dcb0a5221430c2cb39c47fc6947ae123e1a7ffd1514ad32dc03b5b48f21c"

session=HostSession()
token="B1F503A9"  # deterministic test fixture, NOT generated by actual MCU
start={"event":"ACQ_START","mode":"ai_test","phase":"purging","cycle":1,
       "cycles_total":30,"purge_s":25,"collect_s":5,
       "fw_build_id":BUILD_ID,"ai_session_token":token}
session.feed(json.dumps(start))
for row in rows:
    frame={
        "timestamp":int(row["timestamp"]),
        "cycle":int(row["run_id"]),
        "phase":row["phase"],
        "sample_idx":int(row["sample_idx"]),
    }
    frame.update({s:int(row[s]) for s in ADC_COLUMNS})
    session.feed(json.dumps(frame))
_,status=session.feed(json.dumps({"event":"ACQ_COMPLETE","cycles":30,
                                  "total_samples":900}))
assert status["status"]=="CAPTURE_COMPLETE"
cmd,status=session.feed(json.dumps({"event":"AI_AWAITING_RESULT",
                                    "token":token,"samples":900,"window_ms":30000}),
                        allow_predict=True,model_path=model,metadata_path=meta)
assert status["status"]=="RESULT_READY_FOR_SUPERVISED_TX"
assert cmd==wire_command(token,status["roast"])
assert status["roast"]=="dark"
_,ack=session.feed(json.dumps({"event":"AI_RESULT_ACK","token":token,
                              "roast":status["roast"]}))
assert ack["status"]=="MCU_ACK_CONFIRMED"

print(json.dumps({
    "status":"RF30_PI_ACTUAL_MODEL_TO_UART_PACKET_OFFLINE_PASS",
    "csv_sha256":source_digest,
    "model_sha256":sha,
    "cycles":30,"sensor_samples":900,
    "roast_predicted":status["roast"],
    "uart_packet_generated_ascii":cmd.decode(),
    "mcu_ack":"SIMULATED_ONLY",
    "port_opened":False,
    "uart_tx_bytes_sent":0,
    "lcd_physical_updated":False,
    "new_coffee_blind_test":False,
},ensure_ascii=True))
